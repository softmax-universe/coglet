"""ADR-0030 opt-in naming profile. Frozen inputs are imported, never edited.

Derive only rules transitively affected by capability-name; unrelated names,
fields, budgets, manifest format versions and contracts remain unchanged.
"""
import argparse
import copy
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
FAMILIES = ('common', 'abi', 'surface', 'database')
COMPONENT = r'[a-z][a-z0-9_]{0,31}'
PATTERN = rf'^({COMPONENT}\.{COMPONENT}|softmax\.app\.{COMPONENT})(?![\s\S])'
# Preserve quoted literals and map field names while renaming references.
TOKEN = re.compile(r'"(?:\\.|[^"\\])*"|[a-zA-Z_$][a-zA-Z0-9_$-]*')


def sources():
    definitions, cddl = {}, {}
    for family in FAMILIES:
        schema = json.loads((ROOT / f'spec/messages/{family}.schema.json').read_text())
        for name, value in schema['$defs'].items():
            definitions[family, name] = value
        text = (ROOT / f'spec/messages/{family}.cddl').read_text()
        text = '\n'.join(line.split(';', 1)[0] for line in text.splitlines())
        matches = list(re.finditer(r'^([\w$-]+)\s*=\s*', text, re.M))
        for i, match in enumerate(matches):
            end = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            cddl[family, match[1]] = text[match.end():end].strip()
    return definitions, cddl


def references(value, family):
    if isinstance(value, dict):
        if '$ref' in value:
            source, name = value['$ref'].split('#/$defs/')
            yield (source.rsplit('/', 1)[-1].removesuffix('.schema.json') or family, name)
        for child in value.values():
            yield from references(child, family)
    elif isinstance(value, list):
        for child in value:
            yield from references(child, family)


def build():
    definitions, cddl = sources()
    affected = {('common', 'capability-name')}
    while True:
        expanded = affected | {key for key, value in definitions.items()
                               if affected.intersection(references(value, key[0]))}
        if expanded == affected:
            break
        affected = expanded
    # CDDL imports use globally unique rule names. Fail instead of guessing if
    # a future family adds a same-named definition with different semantics.
    names = {name for _, name in affected}
    if len(names) != len(affected):
        raise ValueError('ambiguous profile rule names')

    def rewrite(value, family):
        if isinstance(value, list):
            return [rewrite(x, family) for x in value]
        if not isinstance(value, dict):
            return value
        result = {k: rewrite(v, family) for k, v in value.items()}
        if '$ref' in value:
            source, name = value['$ref'].split('#/$defs/')
            target = source.rsplit('/', 1)[-1].removesuffix('.schema.json') or family
            result['$ref'] = (f'#/$defs/s02-{name}' if (target, name) in affected
                              else f'{target}.schema.json#/$defs/{name}')
        return result

    out, lines = {}, ['; Generated by build_surface02.py; import common/abi/surface/database unchanged.']
    for family, name in sorted(affected):
        key = f's02-{name}'
        out[key] = rewrite(copy.deepcopy(definitions[family, name]), family)
        if name == 'capability-name':
            out[key] = {'type': 'string', 'pattern': PATTERN}
            body = 'tstr .regexp ' + json.dumps(PATTERN.removesuffix(r'(?![\s\S])') + '$')
        else:
            body = TOKEN.sub(lambda m: 's02-' + m[0] if m[0] in names
                             and not re.match(r'\s*:', m.string[m.end():]) else m[0],
                             cddl[family, name])
        lines.append(key + ' = ' + body)
    roots = ['s02-surface-message', 's02-event', 's02-action', 's02-manifest', 's02-db-manifest',
             's02-trace', 's02-db-trace']
    lines.insert(1, 'surface02 = ' + ' / '.join(roots))
    schema = {'$schema': 'https://json-schema.org/draft/2020-12/schema',
              '$id': 'https://coglet.dev/spec/messages/surface02.schema.json',
              'title': 'Explicitly provisioned surface-0.2 contracts',
              'anyOf': [{'$ref': '#/$defs/' + name} for name in roots], '$defs': out}
    return '\n'.join(lines) + '\n', json.dumps(schema, indent=2) + '\n'


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for suffix, content in zip(('cddl', 'schema.json'), build()):
        path = ROOT / f'spec/messages/surface02.{suffix}'
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'stale profile contract: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
