"""Generate ADR-0016 closed sandbox schemas and semantic golden fixtures."""
import copy
import json
from pathlib import Path
import sys

from test_common import encode

ROOT = Path(__file__).resolve().parents[2]


def integer(low, high):
    return dict(type='integer', minimum=low, maximum=high)


def record(fields):
    return dict(type='object', properties=fields, required=list(fields), additionalProperties=False)


HASH = dict(type='string', pattern='^[0-9a-f]{64}(?![\\s\\S])')
DEFS = {
    'gridbot-state': record(dict(x=integer(0, 63), y=integer(0, 63),
        goal_x=integer(0, 63), goal_y=integer(0, 63), width=integer(2, 64),
        height=integer(2, 64), steps=integer(0, 10000), done=dict(type='boolean'), state_hash=HASH)),
    'gridbot-move': record(dict(direction=dict(enum=['north', 'south', 'east', 'west']))),
    'cartpole-state': record({**{k: integer(-2147483648, 2147483647)
        for k in ('x', 'velocity', 'angle', 'angular_velocity')},
        'steps': integer(0, 10000), 'done': dict(type='boolean'), 'state_hash': HASH}),
    'cartpole-force': record(dict(direction=dict(enum=['left', 'right']))),
}
VALUES = {
    'gridbot-state': dict(x=0, y=0, goal_x=1, goal_y=1, width=8, height=8,
                          steps=0, done=False, state_hash='0'*64),
    'gridbot-move': dict(direction='east'),
    'cartpole-state': dict(x=0, velocity=-1, angle=1, angular_velocity=0,
                           steps=0, done=False, state_hash='0'*64),
    'cartpole-force': dict(direction='right'),
}


def cddl_field(shape):
    if 'enum' in shape:
        return '(' + ' / '.join(json.dumps(v) for v in shape['enum']) + ')'
    if shape['type'] == 'integer':
        return f'({shape["minimum"]}..{shape["maximum"]})'
    if shape['type'] == 'boolean':
        return 'bool'
    return 'tstr .regexp "[0-9a-f]{64}"'


def outputs():
    names = list(DEFS)
    cddl = '; ADR-0016. Import common.cddl. Generated by build_sandbox.py.\n'
    cddl += 'sandbox-entry = sandbox-profile\n'
    for name, schema in DEFS.items():
        cddl += name + ' = {' + ', '.join(json.dumps(k) + ': ' + cddl_field(v)
            for k, v in schema['properties'].items()) + '}\n'
    cddl += 'sandbox-profile = ' + ' / '.join(names) + '\n'
    schema = {'$schema': 'https://json-schema.org/draft/2020-12/schema',
        '$id': 'https://coglet.dev/spec/messages/sandbox.schema.json',
        '$ref': '#/$defs/sandbox-profile', '$defs': {**DEFS,
        'sandbox-profile': {'anyOf': [{'$ref': '#/$defs/' + n} for n in names]}}}
    fixtures = []
    for name, good in VALUES.items():
        cases = [('valid', good, True), ('unknown-field', dict(good, extra=True), False)]
        for key, field in DEFS[name]['properties'].items():
            missing = copy.deepcopy(good)
            del missing[key]
            cases.append(('missing-' + key, missing, False))
            for i, bad in enumerate((None, [], {}, True, 'bad')):
                if field.get('type') == 'boolean' and bad is True:
                    continue
                cases.append((f'type-{key}-{i}', dict(good, **{key:bad}), False))
            if field.get('type') == 'integer':
                for value in (field['minimum'] - 1, field['maximum'] + 1):
                    cases.append((f'bound-{key}-{value}', dict(good, **{key:value}), False))
        if 'state_hash' in good:
            cases.append(('hash-newline', dict(good, state_hash='0'*64+'\n'), False))
        else:
            cases.append(('wrong-direction', dict(direction='up'), False))
        for suffix, value, valid in cases:
            fixtures.append(dict(name=name+'-'+suffix, type=name, valid=valid, value=value,
                **({'cbor_hex': encode(value).hex()} if valid else {})))
    dumps = lambda v: json.dumps(v, indent=2) + '\n'
    return {'spec/messages/sandbox.cddl': cddl,
        'spec/messages/sandbox.schema.json': dumps(schema),
        'spec/fixtures/sandbox/cases.json': dumps(fixtures)}


if __name__ == '__main__':
    for path, data in outputs().items():
        dest = ROOT / path
        if '--check' in sys.argv:
            assert dest.read_text() == data, path
        else:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(data)
