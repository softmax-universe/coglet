import importlib.util
import os
from pathlib import Path
import shutil
import subprocess
import tempfile
import unittest

ROOT = Path(__file__).resolve().parents[1]


def load(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / 'codegen' / f'{name}.py')
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


generate = load('cddl')
emit_go = load('emit_go')


def spec_rules():
    contracts = load('contracts')
    return generate.parse_files({p.stem: p.read_text() for p in contracts.schema_paths(ROOT)})


def find_go():
    for candidate in (os.environ.get('GO'), shutil.which('go')):
        if candidate and Path(candidate).exists():
            return candidate
    return None


class GoEmitterTests(unittest.TestCase):
    def test_deterministic_single_file_and_committed_output_current(self):
        rules = spec_rules()
        out = emit_go.generate(rules)
        self.assertEqual(list(out), ['sdk/surface-go/types/generated.go'])
        self.assertEqual(out, emit_go.generate(rules))
        text = out['sdk/surface-go/types/generated.go']
        self.assertTrue(text.startswith('// Code generated by codegen/run. DO NOT EDIT.'))
        self.assertEqual((ROOT / 'sdk/surface-go/types/generated.go').read_text(), text)

    def test_spec_shapes(self):
        text = emit_go.generate(spec_rules())['sdk/surface-go/types/generated.go']
        for expected in ('type Event struct {', 'type ActionAccept interface {', 'type ActionAccept1 struct {',
                         'type ActionOutcome2 struct {', 'Details   *CommonProfileMap', 'Seq           CommonUint64',
                         'type ProfileMap = map[string]CommonProfileValue', 'type SourceId = string',
                         'func DecodeActionAccept(raw []byte)'):
            self.assertIn(expected, text)

    def test_keywords_and_sanitized_names(self):
        rules = generate.parse('thing = {type: tstr, func: tstr, range: tstr, go: tstr, "x.y": tstr, ? "9": tstr}'
                               .replace(', ? "9": tstr', ''))
        text = emit_go.generate(rules)['sdk/surface-go/types/generated.go']
        for field in ('Type ', 'Func ', 'Range ', 'Go ', 'XY '):
            self.assertIn('\t' + field, text)
        self.assertIn('m["x.y"] = v.XY', text)

    def test_ambiguity_fails_closed(self):
        cases = {
            'field collision': 'thing = {a-b: tstr, a_b: tstr}',
            'case collision': 'thing = {type: tstr, "Type": tstr}',
            'rule collision': 'a-b = tstr\na_b = tstr',
            'symbol collision': 'event = {a: tstr}\ndecode-event = tstr',
            'variant collision': 'x = {a: true} / {a: false}\nx1 = tstr',
            'reserved member': 'thing = {to-cbor: tstr}\nother = {"ToValue": tstr}',
            'no identifier': 'thing = {"é": tstr}',
            'digit start': 'thing = {"9": tstr}',
            'recursive alias': 'loop = [* loop]',
        }
        for name, source in cases.items():
            with self.subTest(name):
                with self.assertRaises(ValueError):
                    emit_go.generate(generate.parse(source))

    def test_qualified_unique_aliases_preserve_native_identity(self):
        rules = generate.parse_files({'common': 'item = {value: tstr}\nbox = {item: item}'})
        out = emit_go.Emitter(rules).generate()
        self.assertIn('type CommonItem = Item', out)
        self.assertIn('type CommonBox = Box', out)

    def test_v2_node_mapping(self):
        text = {'op': 'primitive', 'name': 'tstr'}
        rules = {
            'file::text': {'op': 'intersection', 'items': [text, {'op': 'size', 'min': 1, 'max': 2}]},
            'defaulted': {'op': 'default', 'item': {'op': 'array', 'item': text, 'min': 0, 'max': 2}, 'value': []},
            'tuple': {'op': 'tuple', 'items': [{'type': text, 'min': 0, 'max': 1}]},
            'open': {'op': 'record', 'fields': [], 'rest': {'item': text, 'min': 0, 'key': text}},
        }
        # Emitter mapping is tested separately from the compiler-owned IR guard.
        emitter = emit_go.Emitter(rules)
        self.assertEqual(emitter.go_type(rules['file::text']), 'string')
        self.assertEqual(emitter.go_type(rules['defaulted']), '[]string')
        self.assertEqual(emitter.go_type(rules['tuple']), '[]any')
        out = emitter.generate()
        self.assertIn('type FileText = string', out)
        self.assertIn('Rest map[string]string', out)
        self.assertIn('codec.AsList(x, codec.AsString)', out)

    def test_go_string_quoting(self):
        self.assertEqual(emit_go.go_string('a"b\\c\n\x01é'), '"a\\"b\\\\c\\n\\x01é"')

    @unittest.skipUnless(find_go(), 'go toolchain not available')
    def test_generated_code_compiles_and_is_gofmt_clean(self):
        go = find_go()
        rules = generate.parse(
            'thing = {type: tstr, func: tstr, range: tstr, go: tstr, chan: [* uint], ? select: bool}\n'
            'uint = 0..18446744073709551615\n'
            'pick = {kind: "a", v: uint} / {kind: "b", w: tstr}\n'
            'blob = {* tstr => thing}\nfree = thing / uint\n'
            'surface02-s02-capability-name = tstr\n'
            'long = {required: [* surface02-s02-capability-name], ? optional: [* surface02-s02-capability-name], nested: [* [* surface02-s02-capability-name]], mapped: {* tstr => [* surface02-s02-capability-name]}}\n')
        with tempfile.TemporaryDirectory(dir=os.environ.get('TMPDIR')) as temp:
            mod = Path(temp)
            shutil.copytree(ROOT / 'sdk/surface-go/codec', mod / 'codec', ignore=shutil.ignore_patterns('*_test.go'))
            (mod / 'go.mod').write_text('module github.com/softmax-universe/coglet/sdk/surface-go\n\ngo 1.23.0\n')
            for path, content in emit_go.generate(rules).items():
                dest = mod / path.removeprefix('sdk/surface-go/')
                dest.parent.mkdir(parents=True)
                dest.write_text(content)
            env = dict(os.environ, GOFLAGS='-mod=mod')
            subprocess.run([go, 'vet', './...'], cwd=mod, env=env, check=True, capture_output=True, text=True)
            gofmt = Path(go).with_name('gofmt')
            if gofmt.exists():
                result = subprocess.run([str(gofmt), '-l', '.'], cwd=mod, capture_output=True, text=True, check=True)
                self.assertEqual(result.stdout, '')

    @unittest.skipUnless(find_go(), 'go toolchain not available')
    def test_qualified_spec_native_conversions(self):
        with tempfile.TemporaryDirectory(dir=os.environ.get('TMPDIR')) as temp:
            mod = Path(temp) / 'surface-go'
            shutil.copytree(ROOT / 'sdk/surface-go', mod)
            (mod / 'types/generated.go').write_text(emit_go.Emitter(spec_rules()).generate())
            result = subprocess.run([str(find_go()), 'test', './...', '-run', 'TestTyped|TestV2', '-count=1'],
                                    cwd=mod, capture_output=True, text=True)
            self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
